import asyncio
import hashlib
import os
from typing import List, Optional, Tuple
from PIL import Image, ImageDraw, ImageFont
from app.config import get_settings
from app.core.logging import get_logger
from app.providers.base import BaseFootageProvider, FootageAsset

logger = get_logger("fallback_provider")
settings = get_settings()


class FallbackProvider(BaseFootageProvider):
    """
    Deterministic local visual generator.
    Generates styled, motion-animated visual cards with typography and badges.
    Never presents assets as licensed stock footage; clearly identifies them as local fallback visuals.
    """

    @property
    def provider_name(self) -> str:
        return "local_fallback"

    def is_configured(self) -> bool:
        return True  # Always available locally

    async def search(
        self,
        query: str,
        visual_hint: str,
        aspect_ratio: str,
        avoid: List[str],
        min_duration: float,
        limit: int = 1,
    ) -> List[FootageAsset]:
        text_basis = visual_hint or query or "visual scene"
        hash_id = hashlib.md5(text_basis.encode()).hexdigest()[:10]
        clip_id = f"fallback_{hash_id}"

        # Dimensions based on aspect ratio
        dims = {"16:9": (1920, 1080), "9:16": (1080, 1920), "1:1": (1080, 1080)}
        width, height = dims.get(aspect_ratio, (1920, 1080))

        asset = FootageAsset(
            clip_identifier=clip_id,
            source_provider="local_fallback",
            source_url="local://brolliq/fallback-engine",
            download_url="local://generate",
            thumbnail_url=None,
            license_name="BrollIQ Fallback Visual License",
            license_url="https://brolliq.internal/licenses/fallback",
            attribution="Generated by BrollIQ Procedural Engine (Local Fallback)",
            commercial_use_status="test_environment_only",
            rights_verified=True,
            ai_generated=False,
            selection_reason=f"Synthesized deterministic motion visual for '{text_basis[:60]}...'",
            relevance_score=0.85,
            scoring_method="deterministic_procedural_synthesis",
            duration=max(3.0, min_duration),
            width=width,
            height=height,
            tags=[query, "fallback", "procedural"],
        )
        return [asset]

    async def download_asset(self, asset: FootageAsset, dest_path: str) -> str:
        """Generates the MP4 clip directly using Pillow and FFmpeg."""
        os.makedirs(os.path.dirname(os.path.abspath(dest_path)), exist_ok=True)
        img_temp = dest_path.replace(".mp4", "_card.png")

        # 1. Generate base graphic card with Pillow
        self._create_graphic_card(
            output_image_path=img_temp,
            width=asset.width,
            height=asset.height,
            title=asset.tags[0] if asset.tags else "Scene Visual",
            description=asset.selection_reason,
            badge="BROLLIQ FALLBACK VISUAL",
        )

        # 2. Convert to motion-animated video using 4K supersampled smoothstep Ken Burns
        ffmpeg_bin = settings.get_ffmpeg_executable()
        duration_s = max(3.0, asset.duration)
        fps = 30
        total_frames = max(30, int(duration_s * fps))

        # Canvas supersampling to eliminate sub-pixel integer truncation shaking
        if asset.height > asset.width:
            canvas_w, canvas_h = 2160, 3840  # 9:16 Portrait
        elif asset.width == asset.height:
            canvas_w, canvas_h = 2880, 2880  # 1:1 Square
        else:
            canvas_w, canvas_h = 3840, 2160  # 16:9 Landscape

        # Alternating camera direction
        clip_hash = int(hashlib.md5(asset.clip_identifier.encode()).hexdigest()[:4], 16)
        is_pull_out = (clip_hash % 2 == 1)

        if is_pull_out:
            zoom_expr = (
                f"max(1.0,min(1.10,1.10-0.10*(on/{total_frames})*(on/{total_frames})*(3-2*(on/{total_frames}))))"
            )
        else:
            zoom_expr = (
                f"max(1.0,min(1.10,1.0+0.10*(on/{total_frames})*(on/{total_frames})*(3-2*(on/{total_frames}))))"
            )

        vf = (
            f"scale={canvas_w}:{canvas_h}:flags=lanczos,"
            f"zoompan=z='{zoom_expr}':x='trunc(iw/2-(iw/zoom/2))':y='trunc(ih/2-(ih/zoom/2))':"
            f"d={total_frames}:s={asset.width}x{asset.height}:fps={fps},"
            f"format=yuv420p"
        )

        cmd = [
            ffmpeg_bin,
            "-y",
            "-loop", "1",
            "-i", img_temp,
            "-t", f"{duration_s:.2f}",
            "-vf", vf,
            "-c:v", "libx264",
            "-preset", "ultrafast",
            "-crf", "22",
            "-pix_fmt", "yuv420p",
            dest_path,
        ]

        proc = await asyncio.create_subprocess_exec(
            *cmd,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        _, stderr = await proc.communicate()

        if proc.returncode != 0:
            logger.error(f"FFmpeg fallback video generation failed: {stderr.decode()}")
            # Simple static loop fallback if zoompan has issues
            cmd_simple = [
                ffmpeg_bin, "-y", "-loop", "1", "-i", img_temp,
                "-t", f"{duration_s:.2f}", "-c:v", "libx264",
                "-preset", "ultrafast", "-pix_fmt", "yuv420p", dest_path
            ]
            p2 = await asyncio.create_subprocess_exec(*cmd_simple)
            await p2.communicate()

        # Clean up temp image
        if os.path.exists(img_temp):
            try:
                os.remove(img_temp)
            except Exception:
                pass

        return dest_path

    def _create_graphic_card(
        self,
        output_image_path: str,
        width: int,
        height: int,
        title: str,
        description: str,
        badge: str,
    ) -> None:
        """Renders a sleek dark mode graphic card."""
        img = Image.new("RGB", (width, height), color=(18, 20, 26))
        draw = ImageDraw.Draw(img)

        # Subtle dark gradient / grid lines
        grid_step = max(40, width // 24)
        for x in range(0, width, grid_step):
            draw.line([(x, 0), (x, height)], fill=(28, 32, 42), width=1)
        for y in range(0, height, grid_step):
            draw.line([(0, y), (width, y)], fill=(28, 32, 42), width=1)

        # Border accent
        draw.rectangle(
            [(20, 20), (width - 20, height - 20)],
            outline=(45, 52, 68),
            width=2,
        )

        # Badge box
        badge_box = [(40, 40), (40 + len(badge) * 11 + 24, 76)]
        draw.rounded_rectangle(badge_box, radius=6, fill=(30, 41, 59), outline=(132, 204, 22), width=1)
        draw.text((52, 48), badge, fill=(132, 204, 22))

        # Main text
        clean_title = (title[:65] + "...") if len(title) > 65 else title
        clean_desc = (description[:100] + "...") if len(description) > 100 else description

        # Draw card center
        center_y = height // 2
        draw.text((60, center_y - 40), clean_title.upper(), fill=(248, 250, 252))
        draw.text((60, center_y + 10), clean_desc, fill=(148, 163, 184))

        # Bottom watermark
        draw.text((60, height - 70), "INCUBRIX B-ROLL ENGINE | DETERMINISTIC FALLBACK", fill=(100, 116, 139))

        img.save(output_image_path, "PNG")
